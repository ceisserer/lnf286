#!/usr/bin/env python3
"""Generate src/codepage.inc: OEM code page (80h-FFh) -> Unicode tables.

Each table is: dw <codepage number>, then 128 words (Unicode code point
for OEM bytes 80h..FFh, 0 = unmapped).  The list ends with dw 0.
Only the table for the active code page is copied into resident memory.
"""
import sys

CODEPAGES = [437, 850, 852, 855, 857, 860, 861, 862, 863, 865, 866, 737, 775, 869]

def main(out):
    lines = ["; generated by tools/gencp.py - do not edit", "cp_tables:"]
    for cp in CODEPAGES:
        lines.append(f"\tdw {cp}")
        vals = []
        for b in range(0x80, 0x100):
            ch = bytes([b]).decode(f"cp{cp}", errors="replace")
            vals.append(0 if ch == "�" else ord(ch))
        for i in range(0, 128, 8):
            lines.append("\tdw " + ",".join(f"0{v:04X}h" for v in vals[i:i + 8]))
    lines.append("\tdw 0")
    with open(out, "w", newline="\n") as f:
        f.write("\n".join(lines) + "\n")

if __name__ == "__main__":
    main(sys.argv[1] if len(sys.argv) > 1 else "src/codepage.inc")
